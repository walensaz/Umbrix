package umbrix.ui.timeline

import java.time.Instant
import java.time.ZoneId
import java.time.format.DateTimeFormatter

/**
 * Exports collected forensic timeline events into professional incident reports,
 * consolidated logs, or structured JSON data.
 */
object IncidentReportExporter {

    private val EXPORT_DATE_FORMAT = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss z")
        .withZone(ZoneId.systemDefault())

    /**
     * Generates a GitHub/Slack-ready Markdown Incident Post-Mortem Report.
     */
    fun generateMarkdownReport(
        events: List<TimelineEvent>,
        reportTitle: String = "Incident Timeline Analysis"
    ): String {
        val nowStr = EXPORT_DATE_FORMAT.format(Instant.now())
        val builder = StringBuilder()

        builder.appendLine("# $reportTitle")
        builder.appendLine()
        builder.appendLine("> Generated by **Umbrix Log Workstation** on `$nowStr`  ")
        builder.appendLine("> Total Events Analyzed: **${events.size}**")
        builder.appendLine()

        if (events.isEmpty()) {
            builder.appendLine("_No events captured in timeline._")
            return builder.toString()
        }

        // Summary Table
        builder.appendLine("## Chronological Event Summary")
        builder.appendLine()
        builder.appendLine("| # | Timestamp | Δt | Source File | Line | Tag | Note |")
        builder.appendLine("|:--|:---|:---|:---|:---|:---|:---|")

        var previousTimestampMicros = 0L

        for (i in events.indices) {
            val event = events[i]
            val timeStr = TimelineFormatters.formatTimestamp(event.timestampMicros, includeDate = true)
            val deltaStr = if (i == 0 || previousTimestampMicros == 0L || event.timestampMicros == 0L) {
                "—"
            } else {
                TimelineFormatters.formatDelta(event.timestampMicros - previousTimestampMicros)
            }
            if (event.timestampMicros != 0L) {
                previousTimestampMicros = event.timestampMicros
            }

            val noteEscaped = if (event.userNote.isNotBlank()) event.userNote.replace("|", "\\|") else "—"
            builder.appendLine("| ${i + 1} | `$timeStr` | `$deltaStr` | `${event.sourceDocumentTitle}` | `L${event.lineIndex + 1}` | **${event.tag.displayName}** | $noteEscaped |")
        }

        builder.appendLine()
        builder.appendLine("---")
        builder.appendLine()

        // Detailed Forensic Trace Section
        builder.appendLine("## Detailed Event Records")
        builder.appendLine()

        for (i in events.indices) {
            val event = events[i]
            val timeStr = TimelineFormatters.formatTimestamp(event.timestampMicros, includeDate = true)
            builder.appendLine("### Event ${i + 1}: [${event.tag.displayName}] ${event.sourceDocumentTitle} (Line ${event.lineIndex + 1})")
            builder.appendLine("- **Timestamp:** `$timeStr`")
            builder.appendLine("- **Source:** `${event.sourceDocumentPath}`")
            if (event.userNote.isNotBlank()) {
                builder.appendLine("- **Analyst Notes:** ${event.userNote}")
            }
            builder.appendLine()
            builder.appendLine("```log")
            builder.appendLine(event.lineContent)
            builder.appendLine("```")
            builder.appendLine()
        }

        return builder.toString()
    }

    /**
     * Generates a chronologically merged raw log file with provenance comments.
     */
    fun generateConsolidatedLog(events: List<TimelineEvent>): String {
        val builder = StringBuilder()
        for (i in events.indices) {
            val event = events[i]
            val timeStr = TimelineFormatters.formatTimestamp(event.timestampMicros, includeDate = true)
            builder.appendLine("# --- [${event.sourceDocumentTitle}:${event.lineIndex + 1}] [$timeStr] [${event.tag.displayName}] ---")
            if (event.userNote.isNotBlank()) {
                builder.appendLine("# Note: ${event.userNote}")
            }
            builder.appendLine(event.lineContent)
            builder.appendLine()
        }
        return builder.toString()
    }

    /**
     * Generates structured JSON representation of the timeline.
     */
    fun generateJsonArchive(events: List<TimelineEvent>): String {
        val builder = StringBuilder()
        builder.appendLine("[")
        for (i in events.indices) {
            val event = events[i]
            val isLast = i == events.size - 1
            builder.appendLine("  {")
            builder.appendLine("    \"id\": \"${escapeJson(event.id)}\",")
            builder.appendLine("    \"sourcePath\": \"${escapeJson(event.sourceDocumentPath)}\",")
            builder.appendLine("    \"sourceTitle\": \"${escapeJson(event.sourceDocumentTitle)}\",")
            builder.appendLine("    \"lineIndex\": ${event.lineIndex},")
            builder.appendLine("    \"timestampMicros\": ${event.timestampMicros},")
            builder.appendLine("    \"tag\": \"${event.tag.name}\",")
            builder.appendLine("    \"userNote\": \"${escapeJson(event.userNote)}\",")
            builder.appendLine("    \"lineContent\": \"${escapeJson(event.lineContent)}\"")
            builder.appendLine("  }${if (isLast) "" else ","}")
        }
        builder.appendLine("]")
        return builder.toString()
    }

    private fun escapeJson(str: String): String {
        return str.replace("\\", "\\\\")
            .replace("\"", "\\\"")
            .replace("\b", "\\b")
            .replace("\n", "\\n")
            .replace("\r", "\\r")
            .replace("\t", "\\t")
    }
}
